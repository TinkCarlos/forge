export type ErrorCode = keyof typeof definitions;
export interface ErrorDefinition {
  code: ErrorCode; meaning: string; userMessage: string; remedy: string;
  httpStatus: number; retryable: boolean; audience: ErrorAudience;
}
export const ERROR_CODES = Object.freeze(Object.fromEntries(Object.entries(definitions).map(([code, definition]) => [code, Object.freeze({ code, ...definition })]))) as Readonly<Record<ErrorCode, Readonly<ErrorDefinition>>>;
export function isErrorCode(value: unknown): value is ErrorCode {
  return typeof value === "string" && Object.hasOwn(ERROR_CODES, value);
}
